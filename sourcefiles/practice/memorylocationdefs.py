"""The Chrono Trigger memory locations a practice save state can restore:
address, length, bitmask, and the label the save-state editor shows.

Originally transcribed from docs/notes/Memory Locations.txt, but nothing
reads that file any more -- this module is the source of truth. Edit the
rows below directly to add, rename, or re-type a field; pass disabled=True
to hide one from the editor entirely (see
fields.resolve_displayable_and_disabled_fields()). The two rows disabled
today are the non-contiguous 'Unused' masks 0x90 and 0xAA: BitFieldOption's
extract/shift math assumes a contiguous mask, so those two cannot round-trip
through a widget.

Deliberately not the whole of that document. A row is only consulted when
its *start* address lands inside one of a save state's Mem Copy destination
ranges, so rows outside those ranges -- decompressed graphics, tilemaps,
music and battle-engine working RAM, roughly 105 KB of documented RAM the
practice hack never restores -- were dropped as unreachable. If a future
build of the hack copies a region this table doesn't cover, its bytes show
up as "Unknown"; recover the labels from Memory Locations.txt (or this
file's history) and add the rows back.

Several rows can share one address: a byte holding multiple named bit flags
is one row per bit, each with its own bitmask.

Nothing here decides where a field appears on screen. Display grouping is
purely address-based (see grouping.py) so that the many bytes with no row
at all still land beside their named neighbours.

Rows are kept in ascending address order.

The seven playable characters' stat blocks (Crono at 0x7E2600, the rest one
0x50 stride apart) are spelled out individually, but every block is the
byte-for-byte layout of Crono's -- so a row added to one belongs in all
seven. test_character_stat_blocks_are_parallel enforces that.
"""
